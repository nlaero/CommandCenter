/**
 * Stage whisper.cpp Tiny English for the Windows installer.
 *
 * Downloads the same pinned ggml-tiny.en.bin and Windows runtime as
 * Settings → Local AI (see src-tauri/src/local_ai.rs), checks the checksums,
 * and writes the NSIS fragment that copies them into %AppData%\command-center\ai
 * when that install is not already there.
 *
 * The binaries are not committed. Run this on the Windows builder before
 * `tauri build`. It does not print redirected download URLs.
 */
import crypto from "node:crypto";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const MODEL_URL =
  "https://huggingface.co/ggerganov/whisper.cpp/resolve/main/ggml-tiny.en.bin";
export const MODEL_SHA256 =
  "921e4cf8686fdd993dcd081a5da5b6c365bfde1162e72b08d75ac75289920b1f";
export const RUNTIME_URL =
  "https://github.com/ggml-org/whisper.cpp/releases/download/b5454/whisper-bin-x64.zip";
export const RUNTIME_SHA256 =
  "6ba69e3482d7826214f90a6a9c84ca07782aec1e1d0c6a7c30c994fd5d816ccb";

const MODEL_MAX_BYTES = 80 * 1024 * 1024;
const RUNTIME_MAX_BYTES = 20 * 1024 * 1024;
const MODEL_NAME = "ggml-tiny.en.bin";
const RUNTIME_EXE = "whisper-cli.exe";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const payloadDir = path.join(repoRoot, "src-tauri", "windows", "tiny-en");

export function renderInstallJson(modelBytes) {
  if (!Number.isSafeInteger(modelBytes) || modelBytes < 1) {
    throw new Error("The model size is not usable.");
  }
  return `${JSON.stringify(
    {
      modelId: "tiny.en",
      modelLabel: "Tiny English",
      modelBytes,
      modelPath: "ai/models/ggml-tiny.en.bin",
      runtimePath: "ai/runtime/whisper-cli.exe",
    },
    null,
    2,
  )}\n`;
}

function assertSafeRel(rel) {
  const parts = rel.split(/[\\/]/).filter(Boolean);
  if (
    parts.length === 0 ||
    parts.some((part) => part === ".." || part === "." || /["$\r\n]/.test(part))
  ) {
    throw new Error("The runtime archive has a file this installer will not pack.");
  }
}

/** Quote a filesystem path for an NSIS `File` instruction. `$` is escaped. */
export function nsisQuote(value) {
  const text = String(value);
  if (/[\r\n"]/.test(text)) {
    throw new Error("A staged path cannot be packed.");
  }
  return `"${text.replaceAll("$", "$$$$")}"`;
}

/** Quote an NSIS path that already contains variables such as `$APPDATA`. */
function nsisDestination(value) {
  const text = String(value);
  if (/[\r\n"]/.test(text)) {
    throw new Error("A staged path cannot be packed.");
  }
  return `"${text}"`;
}

function wantedRuntimeFile(name) {
  const lower = name.toLowerCase();
  return lower === RUNTIME_EXE || lower.endsWith(".dll");
}

/**
 * Copy whisper-cli.exe and the DLLs beside it into `runtimeDest`.
 * The pinned zip also contains benches, servers, and tests. Those are not
 * part of local captions. Sibling folders (samples, another model) are left behind.
 */
export function copyRuntimeDir(extractedRoot, runtimeDest) {
  const exe = findNamed(extractedRoot, RUNTIME_EXE);
  if (!exe) {
    throw new Error("The runtime archive did not contain whisper-cli.exe.");
  }
  fs.rmSync(runtimeDest, { recursive: true, force: true });
  fs.mkdirSync(runtimeDest, { recursive: true });
  for (const entry of fs.readdirSync(path.dirname(exe), { withFileTypes: true })) {
    if (!entry.isFile() || !wantedRuntimeFile(entry.name)) continue;
    const destName = entry.name.toLowerCase() === RUNTIME_EXE ? RUNTIME_EXE : entry.name;
    fs.copyFileSync(path.join(path.dirname(exe), entry.name), path.join(runtimeDest, destName));
  }
  const staged = path.join(runtimeDest, RUNTIME_EXE);
  if (!fs.statSync(staged).isFile() || fs.statSync(staged).size < 1) {
    throw new Error("The runtime archive did not contain whisper-cli.exe.");
  }
  return staged;
}

function findNamed(dir, name) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const found = findNamed(full, name);
      if (found) return found;
    } else if (entry.name.toLowerCase() === name.toLowerCase()) {
      return full;
    }
  }
  return null;
}

export function renderBundleNsh(options) {
  const lines = [
    "; Generated by scripts/fetch-tiny-en.mjs. Do not edit.",
    "!macro NSIS_HOOK_POSTINSTALL",
    "  ${If} $CcInstallApp <> 1",
    "    Goto cc_tiny_en_done",
    "  ${EndIf}",
    "  SetShellVarContext current",
    '  IfFileExists "$APPDATA\\command-center\\ai\\install.json" cc_tiny_en_done',
    '  DetailPrint "Installing Tiny English"',
    '  CreateDirectory "$APPDATA\\command-center\\ai\\models"',
    '  CreateDirectory "$APPDATA\\command-center\\ai\\runtime"',
    "  SetCompress off",
    '  SetOutPath "$APPDATA\\command-center\\ai\\models"',
    `  File ${nsisQuote(options.modelFile)}`,
  ];
  const runtimeFiles = [...options.runtimeFiles].sort((a, b) => a.localeCompare(b));
  let currentOut = "";
  for (const file of runtimeFiles) {
    const rel = path.relative(options.runtimeDir, file);
    assertSafeRel(rel);
    const parent = path.dirname(rel);
    const out =
      parent === "."
        ? "$APPDATA\\command-center\\ai\\runtime"
        : `$APPDATA\\command-center\\ai\\runtime\\${parent.split(/[\\/]/).join("\\")}`;
    if (out !== currentOut) {
      lines.push(`  CreateDirectory ${nsisDestination(out)}`);
      lines.push(`  SetOutPath ${nsisDestination(out)}`);
      currentOut = out;
    }
    lines.push(`  File ${nsisQuote(file)}`);
  }
  lines.push('  SetOutPath "$APPDATA\\command-center\\ai"');
  lines.push(`  File ${nsisQuote(options.installJson)}`);
  lines.push("  SetCompress auto");
  lines.push("  cc_tiny_en_done:");
  lines.push('  SetOutPath "$INSTDIR"');
  lines.push("!macroend");
  lines.push("");
  return lines.join("\r\n");
}

function unpackZip(zip, dest) {
  const attempts = [
    ["tar", ["-xf", zip, "-C", dest]],
    ["unzip", ["-qo", zip, "-d", dest]],
    ["python3", ["-m", "zipfile", "-e", zip, dest]],
  ];
  for (const [cmd, args] of attempts) {
    fs.rmSync(dest, { recursive: true, force: true });
    fs.mkdirSync(dest, { recursive: true });
    const result = spawnSync(cmd, args, { encoding: "utf8" });
    if (!result.error && result.status === 0) return;
  }
  throw new Error("Could not unpack the speech runtime.");
}

function listFiles(dir) {
  const files = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...listFiles(full));
    else if (entry.isFile()) files.push(full);
  }
  return files;
}

async function download(url, maxBytes) {
  let response;
  try {
    response = await fetch(url, {
      redirect: "follow",
      signal: AbortSignal.timeout(10 * 60 * 1000),
      headers: { "user-agent": "CommandCenter/0.1 (local speech model)" },
    });
  } catch {
    throw new Error("Could not download the local AI.");
  }
  if (!response.ok) {
    throw new Error(`Could not download the local AI (HTTP ${response.status}).`);
  }
  let finalUrl = "";
  try {
    finalUrl = new URL(response.url).protocol;
  } catch {
    finalUrl = "";
  }
  if (finalUrl !== "https:") {
    throw new Error("The download left https.");
  }
  const bytes = Buffer.from(await response.arrayBuffer());
  if (bytes.length < 1) throw new Error("The download was empty.");
  if (bytes.length > maxBytes) throw new Error("The download is larger than the pinned file.");
  return bytes;
}

function sha256(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

async function hashedFile(file) {
  const hash = crypto.createHash("sha256");
  await new Promise((resolve, reject) => {
    const stream = fs.createReadStream(file);
    stream.on("error", reject);
    stream.on("data", (chunk) => hash.update(chunk));
    stream.on("end", resolve);
  });
  return hash.digest("hex");
}

async function stagePayload() {
  fs.mkdirSync(payloadDir, { recursive: true });
  const modelFile = path.join(payloadDir, MODEL_NAME);
  let modelBytes;
  if (fs.existsSync(modelFile) && (await hashedFile(modelFile)) === MODEL_SHA256) {
    modelBytes = fs.statSync(modelFile).size;
    console.log(`Tiny English checksum ok (${modelBytes} bytes).`);
  } else {
    console.log("Downloading Tiny English.");
    const bytes = await download(MODEL_URL, MODEL_MAX_BYTES);
    if (sha256(bytes) !== MODEL_SHA256) {
      throw new Error("The download did not match the expected checksum.");
    }
    const partial = `${modelFile}.partial`;
    await fs.promises.writeFile(partial, bytes);
    await fs.promises.rename(partial, modelFile);
    modelBytes = bytes.length;
    console.log(`Tiny English checksum ok (${modelBytes} bytes).`);
  }

  console.log("Downloading the speech runtime.");
  const zipBytes = await download(RUNTIME_URL, RUNTIME_MAX_BYTES);
  if (sha256(zipBytes) !== RUNTIME_SHA256) {
    throw new Error("The download did not match the expected checksum.");
  }
  console.log("Speech runtime checksum ok.");
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "cc-tiny-en-"));
  try {
    const zip = path.join(tmp, "runtime.zip");
    fs.writeFileSync(zip, zipBytes);
    const extracted = path.join(tmp, "extracted");
    unpackZip(zip, extracted);
    const runtimeDir = path.join(payloadDir, "runtime");
    copyRuntimeDir(extracted, runtimeDir);
    const installJson = path.join(payloadDir, "install.json");
    fs.writeFileSync(installJson, renderInstallJson(modelBytes));
    const bundle = renderBundleNsh({
      modelFile,
      runtimeDir,
      runtimeFiles: listFiles(runtimeDir),
      installJson,
    });
    fs.writeFileSync(path.join(payloadDir, "bundle.nsh"), bundle);
    console.log("Staged Tiny English for the Windows installer.");
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
}

export async function expectInstalled() {
  const appData = process.env.APPDATA;
  if (!appData) throw new Error("APPDATA is not set.");
  const root = path.join(appData, "command-center");
  const markerPath = path.join(root, "ai", "install.json");
  if (!fs.existsSync(markerPath)) {
    throw new Error("Tiny English was not installed.");
  }
  const marker = JSON.parse(fs.readFileSync(markerPath, "utf8"));
  if (marker.modelId !== "tiny.en" || marker.modelLabel !== "Tiny English") {
    throw new Error("The installed model is not Tiny English.");
  }
  if (marker.modelPath !== "ai/models/ggml-tiny.en.bin") {
    throw new Error("The installed model is not in the expected place.");
  }
  if (marker.runtimePath !== "ai/runtime/whisper-cli.exe") {
    throw new Error("The speech runtime is not in the expected place.");
  }
  const model = path.join(root, ...marker.modelPath.split("/"));
  const runtime = path.join(root, ...marker.runtimePath.split("/"));
  if (!fs.existsSync(model) || !fs.existsSync(runtime)) {
    throw new Error("Tiny English was not installed.");
  }
  if (fs.statSync(model).size !== marker.modelBytes) {
    throw new Error("The installed model size does not match.");
  }
  if ((await hashedFile(model)) !== MODEL_SHA256) {
    throw new Error("The installed model did not match the expected checksum.");
  }
  const started = spawnSync(runtime, ["-h"], {
    cwd: path.dirname(runtime),
    timeout: 20_000,
    windowsHide: true,
  });
  if (started.error || started.status == null || (started.status !== 0 && started.status !== 1)) {
    throw new Error("The speech runtime did not start.");
  }
  console.log(`Tiny English is installed (${marker.modelBytes} bytes).`);
}

async function main() {
  const command = process.argv[2];
  if (!command) {
    await stagePayload();
    return;
  }
  if (command === "--expect-installed") {
    await expectInstalled();
    return;
  }
  throw new Error("Unknown argument.");
}

const invoked =
  process.argv[1] &&
  path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (invoked) {
  main().catch((err) => {
    const message = err instanceof Error ? err.message : "Could not stage Tiny English.";
    console.error(message);
    process.exit(1);
  });
}
